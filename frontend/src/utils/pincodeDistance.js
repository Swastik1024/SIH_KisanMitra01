/**
 * Get approximate lat/lng for an Indian pincode.
 * Falls back by trying shorter prefixes if the 3-digit key isn't found.
 * @param {string} pincode
 * @returns {[number, number] | null} [lat, lng] or null
 */
export function pincodeToCoords(pincode) {
  if (!pincode || String(pincode).length < 4) return null;
  const pin = String(pincode).replace(/\s/g, '');
  const p3 = pin.slice(0, 3);
  if (PINCODE_COORDS[p3]) return PINCODE_COORDS[p3];
  // fallback: try first 2 chars + '0'
  const p2 = pin.slice(0, 2) + '0';
  if (PINCODE_COORDS[p2]) return PINCODE_COORDS[p2];
  return null;
}

/**
 * Haversine distance between two [lat, lng] pairs in km.
 * @param {number} lat1
 * @param {number} lon1
 * @param {number} lat2
 * @param {number} lon2
 * @returns {number} distance in km
 */
export function haversineKm(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c);
}

/**
 * Compute approximate road distance between two pincodes.
 * Uses Haversine * 1.3 (road factor) as a reasonable approximation.
 * @param {string} pin1
 * @param {string} pin2
 * @returns {number | null} approximate km or null if either pincode unknown
 */
export function approxDistanceKm(pin1, pin2) {
  const c1 = pincodeToCoords(pin1);
  const c2 = pincodeToCoords(pin2);
  if (!c1 || !c2) return null;
  const straight = haversineKm(c1[0], c1[1], c2[0], c2[1]);
  // Road distance ≈ straight-line × 1.3 (India average road factor)
  return Math.round(straight * 1.3);
}

/**
 * Format distance for display.
 * @param {number | null} km
 * @returns {string}
 */
export function formatDistance(km) {
  if (km === null) return null;
  if (km < 5) return 'Nearby (<5 km)';
  if (km < 50) return `~${km} km away`;
  if (km < 500) return `~${Math.round(km / 10) * 10} km away`;
  return `~${Math.round(km / 100) * 100} km away`;
}
